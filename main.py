# main.py

import numpy as np

from utils.map_generator import MapGenerator
from utils.car_model import KinematicVehicle
from utils.sensor import LineSensorArray
from utils.control import LineController
from utils.visualization import animate_vehicle


# ============================================================
# 맵 생성
# ============================================================

Y_MIN = -10
Y_MAX = 150


game_map = MapGenerator(
    x_min=-30,
    x_max=30,
    y_min=Y_MIN,
    y_max=Y_MAX,
    default_reflectance=1023
)


# ============================================================
# 검은색 라인 생성
# ============================================================

for x in range(-1, 2):

    for y in range(Y_MIN, Y_MAX + 1):

        game_map.set_reflectance(
            x=x,
            y=y,
            value=0
        )


# ============================================================
# 전체 맵에 랜덤 노이즈 추가
# ============================================================

NOISE_LEVEL = 50


for x in range(-30, 31):

    for y in range(Y_MIN, Y_MAX + 1):

        current_value = game_map.get_reflectance(
            x,
            y
        )


        noise = np.random.randint(
            -NOISE_LEVEL,
            NOISE_LEVEL + 1
        )


        new_value = (
            current_value
            +
            noise
        )


        new_value = np.clip(
            new_value,
            0,
            1023
        )


        game_map.set_reflectance(
            x=x,
            y=y,
            value=new_value
        )


# ============================================================
# 차량 모델
# ============================================================

DT = 0.02


vehicle = KinematicVehicle(
    track_width=20,
    dt=DT
)


# ============================================================
# 센서
# ============================================================

S = 2.5


sensor = LineSensorArray(
    sensor_distance=10,
    sensor_spacing=S
)


# ============================================================
# 제어기
# ============================================================

controller = LineController(
    base_speed=10.0,
    kp=0.5,
    ki=0.01,
    kd=0.1,
    dt=DT,
    sensor_spacing=S,
    threshold=200.0,
    max_speed=10.0,
    min_speed=-5.0
)


# ============================================================
# 초기 차량 상태
# ============================================================

state = np.array(
    [
        2.0,
        0.0,
        np.pi / 2
    ]
)


# ============================================================
# FSM 상태
# ============================================================

LINE_FOLLOW = 0
STOP = 1
TURN_180 = 2


mode = LINE_FOLLOW


# ============================================================
# 정지 시간
# ============================================================

STOP_TIME = 1.0

stop_start_time = None


# ============================================================
# 180도 회전 설정
# ============================================================

TURN_SPEED = 5.0


# ------------------------------------------------------------
# 실험하면서 조절할 값
#
# 예:
# 5.0
# 5.5
# 6.0
# 6.3
# 6.5
# ------------------------------------------------------------

TURN_DURATION = 6.28
# t = Pi * W / |v_R - v_L|
#   = Pi * 20 / |5 - (-5)|
#   ≈ 6.28 s


turn_start_time = None


# ============================================================
# 시뮬레이션
# ============================================================

SIMULATION_TIME = 40


steps = int(
    SIMULATION_TIME / DT
)


trajectory = [
    state.copy()
]


# ============================================================
# 메인 시뮬레이션
# ============================================================

for step in range(steps):


    # ========================================================
    # 현재 시간
    # ========================================================

    current_time = step * DT


    # ========================================================
    # LINE FOLLOW
    # ========================================================

    if mode == LINE_FOLLOW:


        # ----------------------------------------------------
        # 센서 측정
        # ----------------------------------------------------

        sensor_values = sensor.read(
            game_map,
            state
        )


        # ----------------------------------------------------
        # PID 제어
        # ----------------------------------------------------

        control = controller.control(
            sensor_values
        )


        # ----------------------------------------------------
        # y = 100 도착 확인
        # ----------------------------------------------------

        if state[1] >= 100.0:

            mode = STOP

            stop_start_time = current_time


            control = np.array(
                [
                    0.0,
                    0.0
                ]
            )


            print("END REACHED")


    # ========================================================
    # STOP
    # ========================================================

    elif mode == STOP:


        # ----------------------------------------------------
        # 차량 정지
        # ----------------------------------------------------

        control = np.array(
            [
                0.0,
                0.0
            ]
        )


        # ----------------------------------------------------
        # 설정 시간만큼 정지
        # ----------------------------------------------------

        if (
            current_time
            -
            stop_start_time
            >=
            STOP_TIME
        ):

            mode = TURN_180

            turn_start_time = current_time


            print("START TURN")


    # ========================================================
    # TURN 180
    # ========================================================

    elif mode == TURN_180:


        # ----------------------------------------------------
        # 제자리 회전
        #
        # 왼쪽 바퀴 후진
        # 오른쪽 바퀴 전진
        # ----------------------------------------------------

        control = np.array(
            [
                -TURN_SPEED,
                TURN_SPEED
            ]
        )


        # ----------------------------------------------------
        # 회전 경과 시간
        # ----------------------------------------------------

        elapsed_turn_time = (
            current_time
            -
            turn_start_time
        )


        # ----------------------------------------------------
        # 설정한 시간만큼 회전 완료
        # ----------------------------------------------------

        if (
            elapsed_turn_time
            >=
            TURN_DURATION
        ):

            # -----------------------------------------------
            # 회전 종료 후
            # 다시 LINE_FOLLOW로 복귀
            # -----------------------------------------------

            mode = LINE_FOLLOW


            # 일단 정지
            control = np.array(
                [
                    0.0,
                    0.0
                ]
            )


            print("TURN COMPLETE")
            print("RETURN TO LINE FOLLOW")


    # ========================================================
    # 차량 상태 업데이트
    # ========================================================

    state = vehicle.update(
        state,
        control
    )


    # ========================================================
    # Trajectory 저장
    # ========================================================

    trajectory.append(
        state.copy()
    )


# ============================================================
# Trajectory → numpy array
# ============================================================

trajectory = np.array(
    trajectory
)


# ============================================================
# 시각화
# ============================================================

animate_vehicle(
    game_map,
    trajectory,
    DT,
    sensor
)